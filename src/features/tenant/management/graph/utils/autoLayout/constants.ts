/**
 * 自動整列のレイアウト間隔。値はすべて「ノードの箱の端から別の箱の端まで」
 * の距離を指し、配置アルゴリズム全体で下限（最低マージン）として保証される。
 */

/** 列（レイヤー）間に必ず確保する、フロー軸方向の最低マージン */
export const LAYER_GAP = 120;

/**
 * 同一列内で積むノード間・境界バンドと内容の間に必ず確保する、
 * クロス軸方向の最低マージン。間をルートが通るため、
 * フロー軸方向の余裕に近い広さをとる
 */
export const CROSS_GAP = 96;

/** 境界バンド内で並ぶメンバー間の、フロー軸方向の間隔 */
export const MEMBER_GAP = 48;

/** 連結成分（ルートで繋がっていない塊）間の間隔 */
export const COMPONENT_GAP = 96;

/**
 * ノードの間をルートが通り抜けるときに、通常の間隔へ上乗せして確保する
 * 通り道の幅。レーンの占有幅と、またぎオフセットの余白に使う
 */
export const ROUTE_CLEARANCE = 48;

/** 列内順序を接続相手の平均位置へ寄せる緩和計算の反復回数 */
export const ORDERING_SWEEPS = 3;
